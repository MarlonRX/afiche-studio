/**
 * Scaffold generator: writes a generic poster project (index.html +
 * config.json) whose palette/typography come from the scanned tokens.
 * The poster follows the same adaptive pattern as the hand-made projects
 * (#canvas + shared/adaptive.js) so every format derives from the master.
 */

const fs = require('fs');
const path = require('path');
const config = require('../config');

function cap(text) {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

