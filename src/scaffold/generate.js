/** Contrasting ink for text sitting on the accent background. */
function bgTextFor(hex) {
  const { l } = require('./scan').hexToHsl(hex.replace('#', ''));
  return l < 0.55 ? '#ffffff' : '#111111';
}

/**
 * Write the project folder (config.json + index.html).
 * @param {{ name, title, tokens, dir }} opts
 */
function generate({ name, title, tokens, dir }) {
  const cfg = {
    name,
    title,
    description: 'Generic poster generated by `afiche --app` from the app global styles.',
    preset: 'wide',
    width: 1920,
    height: 1080,
    scale: 2,
    outputFormat: 'png',
    brand: {
      colors: {
        background: tokens.colors.background,
        surface: tokens.colors.surface,
        accent: tokens.colors.accent,
        accent2: tokens.colors.accent2,
        text: tokens.colors.text,
      },
      typography: {
        headlineFont: tokens.fonts.display,
        bodyFont: tokens.fonts.body,
        monoFont: tokens.fonts.mono,
      },
    },
  };

  fs.writeFileSync(path.join(dir, 'index.html'), buildHtml({ name, title, tokens }));
  fs.writeFileSync(path.join(dir, 'config.json'), JSON.stringify(cfg, null, 2));

  return { dir, config: cfg };
}

module.exports = { generate, buildHtml, bgTextFor };